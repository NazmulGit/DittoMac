import Foundation

/// A colour theme. `colors` maps upstream Ditto theme keys to "#RRGGBB" strings.
/// An empty `colors` dictionary (the "System" theme) means: use native system colours.
public struct ThemeSpec: Sendable, Equatable {
    public var name: String
    public var colors: [String: String]
    public var isDark: Bool

    public init(name: String, colors: [String: String], isDark: Bool) {
        self.name = name
        self.colors = colors
        self.isDark = isDark
    }

    public func color(_ key: String) -> String? { colors[key] }

    /// Relative luminance (0...1) of a "#RRGGBB" string; nil when malformed.
    public static func luminance(hex: String) -> Double? {
        var h = hex
        if h.hasPrefix("#") { h.removeFirst() }
        guard h.count == 6, let v = UInt32(h, radix: 16) else { return nil }
        let r = Double((v >> 16) & 0xFF) / 255, g = Double((v >> 8) & 0xFF) / 255, b = Double(v & 0xFF) / 255
        return 0.299 * r + 0.587 * g + 0.114 * b
    }
}

